// Builds src/server/churchSchema.ts: the finance schema for a new church's own
// database (multi-church mode).
//
// The baseline is schema/church-finance.sql — the live database's structure,
// exported without data:
//   npx wrangler d1 export church-finance --remote --no-data --output schema/church-finance.sql
// The migration files cannot be replayed from scratch (0001 was edited after
// later ones ran, and they carry BOLCCOP's sample rows and default login), so
// only migrations numbered after the live database's last one are added, as
// steps each church applies once.
//
//   node scripts/build-church-schema.mjs <last migration in the export, e.g. 0024>
import { DatabaseSync } from 'node:sqlite';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const baseline = process.argv[2];
if (!/^\d{4}$/.test(baseline || '')) throw new Error('Usage: node scripts/build-church-schema.mjs <baseline migration number>');

const db = new DatabaseSync(':memory:');
db.exec(readFileSync(new URL('../schema/church-finance.sql', import.meta.url), 'utf8'));
const objects = db.prepare(
  "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name <> 'd1_migrations' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid"
).all();
const schema = objects.map((o) => o.sql.replace(/^CREATE (TABLE|INDEX|UNIQUE INDEX) (?!IF NOT EXISTS)/, 'CREATE $1 IF NOT EXISTS '));

const migrationsDir = new URL('../migrations/', import.meta.url);
const later = readdirSync(migrationsDir)
  .filter((f) => /^\d{4}_.*\.sql$/.test(f) && f.slice(0, 4) > baseline)
  .sort()
  .map((name) => ({ name, sql: readFileSync(new URL(name, migrationsDir), 'utf8') }));

const out = `// Generated by scripts/build-church-schema.mjs — do not edit by hand.
// A new church's database starts from the live schema as of migration ${baseline};
// CHURCH_MIGRATIONS are applied on top, once each, in order.

export const CHURCH_SCHEMA_BASELINE = '${baseline}';

export const CHURCH_SCHEMA: readonly string[] = ${JSON.stringify(schema, null, 2)};

export const CHURCH_MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(later, null, 2)};
`;
writeFileSync(new URL('../src/server/churchSchema.ts', import.meta.url), out);
console.log(`${schema.length} schema statements (baseline ${baseline}), ${later.length} later migration(s): ${later.map((m) => m.name).join(', ') || 'none'}`);
