/**
 * The panel speaks the language OBS is set to: English (the default) or
 * Traditional Chinese. OBS passes it in the page address (?lang=zh-TW); every
 * piece of interface text comes from here, so one screen never mixes the two.
 * What is shown on the slides follows the content (a Chinese Bible, an English one).
 */

export type Lang = 'en' | 'zh';

export const LANG: Lang = (() => {
  try {
    const param = new URLSearchParams(location.search).get('lang') ?? '';
    return param.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
})();

